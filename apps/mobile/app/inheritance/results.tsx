function formatCurrency(amount: number, currency: string): string {
  const sym: Record<string, string> = { NGN: '₦', USD: '$', GBP: '£', EUR: '€', SAR: 'ر.س', AED: 'د.إ', MYR: 'RM' };
  const prefix = sym[currency] ?? currency + ' ';
  return prefix + amount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function formatPercentage(share: number): string {
  return (share * 100).toFixed(2) + '%';
}

function shareTypeBadgeColor(type: string): string {
  if (type === 'FARD')    return colors.secondary;
  if (type === 'ASABAH')  return '#48BB78';
  if (type === 'BLOCKED') return colors.error;
  return colors.textMuted;
}

function shareTypeLabel(type: string): string {
  if (type === 'FARD')    return 'Fard';
  if (type === 'ASABAH')  return 'Asabah';
  if (type === 'BLOCKED') return 'Blocked';
  return '—';
}

export default function InheritanceResultsScreen() {
  const router = useRouter();
  const { result, currency, totalEstate, debts, funeralExpenses, wasiyyah, reset } = useInheritance();
  const [isSaving, setIsSaving] = useState(false);
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);

  if (!result) {
    return (
      <SafeScreen edges={['top', 'bottom', 'left', 'right']}>
        <Header title="Results" />
        <View style={styles.centeredEmpty}>
          <Ionicons name="calculator-outline" size={48} color={colors.textMuted} />
          <Text style={styles.emptyTitle}>No Results Yet</Text>
          <Text style={styles.emptySub}>Go back and complete the calculation.</Text>
          <TouchableOpacity onPress={() => router.back()} style={styles.backBtn}>
            <Text style={styles.backBtnText}>← Back to Summary</Text>
          </TouchableOpacity>
        </View>
      </SafeScreen>
    );
  }

  const r = result as InheritanceResult;

  const activeShares  = r.shares.filter(s => !s.isBlocked && s.shareType !== 'BLOCKED' && s.shareType !== 'NONE');
  const blockedShares = r.shares.filter(s => s.isBlocked || s.shareType === 'BLOCKED');

  const handleShareText = async () => {
    const lines = activeShares.map(s =>
      `${s.label} (×${s.count}): ${s.fractionLabel} = ${formatCurrency(s.totalAmount, currency)} (${formatPercentage(s.shareOfEstate)})`
    );
    const text = [
      'MIZAN — Islamic Inheritance (Mirath) Calculation',
      '─────────────────────────────',
      `Net Estate: ${formatCurrency(r.netEstate, currency)}`,
      `Method: ${r.calculationMethod}${r.awlFactor ? ` (Awl ×${r.awlFactor.toFixed(3)})` : ''}`,
      '',
      'Heir Shares:',
      ...lines,
      '',
      'Generated by MIZAN — Islamic Finance Platform',
    ].join('\n');

    await Share.share({ message: text, title: 'Mirath Calculation' });
  };

  const handleDownloadPDF = async () => {
    try {
      setIsGeneratingPdf(true);
      await pdfService.generateAndShareInheritancePDF(
        r,
        totalEstate,
        debts,
        funeralExpenses,
        wasiyyah,
        currency
      );
    } catch (error) {
      console.error('PDF error:', error);
      Alert.alert('PDF Error', 'Could not generate PDF report. Please try again.');
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const handleSaveResult = async () => {
    setIsSaving(true);
    const ok = await pdfService.saveInheritanceResult(r, totalEstate, currency);
    setIsSaving(false);
    if (ok) {
      Alert.alert('Result Saved! 💚', 'Your Inheritance calculation has been saved to your history.');
    } else {
      Alert.alert('Notice', 'Could not save calculation to history.');
    }
  };

  const handleNewCalculation = () => {
    reset();
    router.replace('/inheritance');
  };

  const handleHome = () => {
    reset();
    router.dismissAll();
    router.replace('/');
  };

  return (
    <SafeScreen edges={['top', 'bottom', 'left', 'right']}>
      <Header title="Inheritance Results" />

      <ScrollView contentContainerStyle={styles.scrollContent} showsVerticalScrollIndicator={false}>

        {/* Method Banner */}
        {r.calculationMethod !== 'NORMAL' && (
          <View style={[styles.methodBanner, r.calculationMethod === 'AWL' ? styles.awlBanner : styles.raddBanner]}>
            <Ionicons
              name={r.calculationMethod === 'AWL' ? 'warning-outline' : 'checkmark-circle-outline'}
              size={18}
              color={r.calculationMethod === 'AWL' ? colors.warning : colors.success}
            />
            <Text style={styles.methodText}>
              {r.calculationMethod === 'AWL'
                ? `ʿAwl applied — shares exceed estate and were reduced proportionally (factor: ${r.awlFactor?.toFixed(3)})`
                : 'Radd applied — surplus returned proportionally to eligible Fard heirs (excluding spouse)'}
            </Text>
          </View>
        )}

        {/* Estate Summary */}
        <View style={styles.estateSummaryRow}>
          <View style={styles.estateSummaryItem}>
            <Text style={styles.estateSummaryLabel}>Net Estate</Text>
            <Text style={styles.estateSummaryValue}>{formatCurrency(r.netEstate, currency)}</Text>
          </View>
          <View style={styles.estateDivider} />
          <View style={styles.estateSummaryItem}>
            <Text style={styles.estateSummaryLabel}>Distributed</Text>
            <Text style={[styles.estateSummaryValue, { color: colors.success }]}>
              {formatCurrency(r.totalAllocated, currency)}
            </Text>
          </View>
          {r.unallocated > 0.01 && (
            <>
              <View style={styles.estateDivider} />
              <View style={styles.estateSummaryItem}>
                <Text style={styles.estateSummaryLabel}>Unallocated</Text>
                <Text style={[styles.estateSummaryValue, { color: colors.warning }]}>
                  {formatCurrency(r.unallocated, currency)}
                </Text>
              </View>
            </>
          )}
        </View>

        {/* Heir Shares */}
        <View style={styles.sectionHeader}>
          <Text style={styles.sectionTitle}>Heir Shares</Text>
          <Text style={styles.sectionSub}>{activeShares.length} heirs</Text>
        </View>

        {activeShares.map((share, index) => (
          <ShareCard key={`${share.key}-${index}`} share={share} currency={currency} />
        ))}

        {/* Blocked Heirs */}
        {blockedShares.length > 0 && (
          <>
            <View style={[styles.sectionHeader, { marginTop: spacing.lg }]}>
              <Text style={styles.sectionTitle}>Blocked Heirs (Hajb)</Text>
              <Text style={styles.sectionSub}>{blockedShares.length} blocked</Text>
            </View>
            <Text style={styles.blockedExplainer}>
              The following heirs are present but receive nothing due to Islamic blocking rules (Hajb Hirman).
            </Text>
            {blockedShares.map((share, index) => (
              <BlockedCard key={`${share.key}-${index}`} share={share} />
            ))}
          </>
        )}

        {/* Reference */}
        <View style={styles.referenceBox}>
          <Text style={styles.referenceTitle}>Quranic Basis</Text>
          <Text style={styles.referenceText}>
            Surah An-Nisa (4:11-12, 4:176) — "Allah instructs you concerning your children…"
          </Text>
          <Text style={[styles.referenceText, { marginTop: spacing.xs }]}>
            Madhhab: {r.madhhab.charAt(0) + r.madhhab.slice(1).toLowerCase()}
          </Text>
        </View>

        {/* Disclaimer */}
        <View style={styles.disclaimer}>
          <Ionicons name="shield-checkmark-outline" size={14} color={colors.textMuted} />
          <Text style={styles.disclaimerText}>
            This is a computational aid. Always consult a qualified Islamic scholar (Mufti) for a formal ruling on your specific situation.
          </Text>
        </View>

        {/* Actions */}
        <View style={styles.actionGrid}>
          <TouchableOpacity style={styles.pdfBtn} onPress={handleDownloadPDF} disabled={isGeneratingPdf}>
            {isGeneratingPdf ? (
              <ActivityIndicator color={colors.primaryDark} />
            ) : (
              <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
                <Ionicons name="document-text-outline" size={18} color={colors.primaryDark} />
                <Text style={styles.pdfBtnText}>Download PDF Report</Text>
              </View>
            )}
          </TouchableOpacity>

          <TouchableOpacity style={styles.saveBtn} onPress={handleSaveResult} disabled={isSaving}>
            {isSaving ? (
              <ActivityIndicator color={colors.secondary} />
            ) : (
              <View style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}>
                <Ionicons name="bookmark-outline" size={18} color={colors.secondary} />
                <Text style={styles.saveBtnText}>Save Result</Text>
              </View>
            )}
          </TouchableOpacity>
        </View>

        <View style={styles.secondaryActionsRow}>
          <TouchableOpacity style={styles.shareTextBtn} onPress={handleShareText}>
            <Ionicons name="share-social-outline" size={18} color={colors.textSecondary} />
            <Text style={styles.shareTextLabel}>Share Summary</Text>
          </TouchableOpacity>

          <Button
            title="New Calculation"
            onPress={handleNewCalculation}
            variant="ghost"
            style={{ flex: 1 }}
          />
        </View>

        <TouchableOpacity style={styles.homeLinkBtn} onPress={handleHome}>
          <Text style={styles.homeLinkText}>← Back to Home</Text>
        </TouchableOpacity>

      </ScrollView>
    </SafeScreen>
  );
}

// ─── Share Card ───────────────────────────────────────────────────────────────

function ShareCard({ share, currency }: { share: ShareResult; currency: string }) {
  const [isExpanded, setIsExpanded] = useState(false);
  const badgeColor = shareTypeBadgeColor(share.shareType);
  const ref = HEIR_REFERENCES[share.key];

  return (
    <View style={shareCardStyles.card}>
      <TouchableOpacity onPress={() => setIsExpanded(!isExpanded)} activeOpacity={0.8}>
        <View style={shareCardStyles.header}>
          <View style={shareCardStyles.labelRow}>
            <Text style={shareCardStyles.label}>{share.label}</Text>
            {share.count > 1 && (
              <Text style={shareCardStyles.count}>(×{share.count})</Text>
            )}
          </View>
          <View style={[shareCardStyles.typeBadge, { backgroundColor: badgeColor + '22', borderColor: badgeColor + '55' }]}>
            <Text style={[shareCardStyles.typeText, { color: badgeColor }]}>
              {shareTypeLabel(share.shareType)}
            </Text>
          </View>
        </View>

        <View style={shareCardStyles.amounts}>
          <View style={shareCardStyles.amountItem}>
            <Text style={shareCardStyles.amountLabel}>Share</Text>
            <Text style={shareCardStyles.fractionText}>{share.fractionLabel}</Text>
          </View>
          <View style={shareCardStyles.amountDivider} />
          <View style={shareCardStyles.amountItem}>
            <Text style={shareCardStyles.amountLabel}>Total</Text>
            <Text style={shareCardStyles.totalText}>{formatCurrency(share.totalAmount, currency)}</Text>
          </View>
          {share.count > 1 && (
            <>
              <View style={shareCardStyles.amountDivider} />
              <View style={shareCardStyles.amountItem}>
                <Text style={shareCardStyles.amountLabel}>Per Person</Text>
                <Text style={shareCardStyles.perPersonText}>{formatCurrency(share.perPersonAmount, currency)}</Text>
              </View>
            </>
          )}
        </View>

        <View style={shareCardStyles.progressBg}>
          <View style={[shareCardStyles.progressFill, { width: `${Math.min(100, share.shareOfEstate * 100)}%` as any }]} />
        </View>
        <Text style={shareCardStyles.percentText}>{formatPercentage(share.shareOfEstate)} of estate</Text>
      </TouchableOpacity>

      {ref && (
        <View style={{ marginTop: spacing.sm }}>
          <TouchableOpacity onPress={() => setIsExpanded(!isExpanded)} style={shareCardStyles.viewMoreBtn}>
            <Text style={shareCardStyles.viewMoreText}>{isExpanded ? 'View Less ▴' : 'View More ▾'}</Text>
          </TouchableOpacity>
          {isExpanded && (
            <View style={shareCardStyles.referenceBox}>
              <Text style={shareCardStyles.refTitle}>📖 {ref.quran}</Text>
              {ref.hadith && <Text style={shareCardStyles.refTitle}>📚 {ref.hadith}</Text>}
              <Text style={shareCardStyles.refText}>{ref.explanation}</Text>
              {ref.madhhabNote && (
                <Text style={shareCardStyles.refNote}>Note: {ref.madhhabNote}</Text>
              )}
            </View>
          )}
        </View>
      )}
    </View>
  );
}

